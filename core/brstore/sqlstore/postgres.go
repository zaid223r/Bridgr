package sqlstore

import (
	"errors"
	"reflect"
	"strconv"
	"strings"
	"time"

	"github.com/zaid223r/Bridgr/core/brschema"
)

// Postgres is the dialect for PostgreSQL through any database/sql driver, such
// as github.com/jackc/pgx/v5/stdlib (driver name "pgx").
var Postgres Dialect = postgresDialect{}

type postgresDialect struct{}

func (postgresDialect) Placeholder(n int) string { return "$" + strconv.Itoa(n) }

func (postgresDialect) Quote(ident string) string {
	return `"` + strings.ReplaceAll(ident, `"`, `""`) + `"`
}

func (postgresDialect) ContainsExpr(column, ph string) string {
	return column + " ILIKE " + ph + ` ESCAPE '\'`
}

func (postgresDialect) ColumnType(f *brschema.Field) string {
	t := f.Type
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	notNull := " NOT NULL"
	if f.Nullable {
		notNull = ""
	}
	switch {
	case t == reflect.TypeFor[time.Time]():
		return "TIMESTAMPTZ" + notNull
	case t.Kind() == reflect.Slice:
		return "BYTEA" // nil []byte is NULL, so byte columns are always nullable
	}
	switch t.Kind() {
	case reflect.Bool:
		return "BOOLEAN" + notNull
	case reflect.String:
		return "TEXT" + notNull
	case reflect.Float32:
		return "REAL" + notNull
	case reflect.Float64:
		return "DOUBLE PRECISION" + notNull
	case reflect.Int8, reflect.Int16, reflect.Uint8:
		return "SMALLINT" + notNull
	case reflect.Int32, reflect.Uint16:
		return "INTEGER" + notNull
	case reflect.Uint, reflect.Uint64:
		return "NUMERIC(20, 0)" + notNull // uint64 doesn't fit BIGINT
	default:
		return "BIGINT" + notNull
	}
}

func (d postgresDialect) AutoIncrementPK(column string) string {
	return d.Quote(column) + " BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
}

// pgError matches github.com/jackc/pgx's *pgconn.PgError (and lib/pq's
// *pq.Error) without importing a driver.
type pgError interface {
	error
	SQLState() string
}

const pgUniqueViolation = "23505"

func (postgresDialect) IsUniqueViolation(err error) bool {
	e, ok := errors.AsType[pgError](err)
	return ok && e.SQLState() == pgUniqueViolation
}

func (postgresDialect) NoLimit() string { return "" }

// SyncSequence is needed because an identity column's sequence doesn't notice
// rows inserted with an explicit id; the next generated id would collide.
func (d postgresDialect) SyncSequence(table, column string) (string, []any) {
	return "SELECT setval(pg_get_serial_sequence($1, $2), GREATEST((SELECT MAX(" +
		d.Quote(column) + ") FROM " + d.Quote(table) + "), 1))", []any{d.Quote(table), column}
}
