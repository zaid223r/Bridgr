// Package api builds the OpenAPI document and serves the docs UI for registered routes.
package api

import (
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"github.com/zaid223r/Bridgr/core/brschema"
	"github.com/zaid223r/Bridgr/core/brstore"
)

// BuildSpec renders the OpenAPI 3.0 document for every route registered with RegisterPath.
func BuildSpec() ([]byte, error) {
	paths := map[string]any{}

	for _, p := range GetPaths() {
		model := mustSchema(p.Model)
		props := ReflectModel(p.Model)
		if pk := model.PrimaryKey; pk != nil {
			switch p.Method {
			case "post":
				delete(props, pk.JSONName)
			case "put", "patch":
				prop := property(pk)
				prop["readOnly"] = true
				props[pk.JSONName] = prop
			}
		}
		pathItem := paths[p.Path]
		if pathItem == nil {
			pathItem = map[string]any{}
			paths[p.Path] = pathItem
		}

		// Detect if path has a parameter (e.g., {id})
		var parameters []map[string]any
		if paramName := extractPathParam(p.Path); paramName != "" {
			parameters = append(parameters, map[string]any{
				"name":     paramName,
				"in":       "path",
				"required": true,
				"schema": map[string]any{
					"type": "string",
				},
			})
		}

		// Add filterable fields as query parameters for GET list endpoints
		if p.Method == "get" && extractPathParam(p.Path) == "" {
			parameters = append(parameters, pagingParameters(model)...)
			for _, f := range model.Filterable {
				parameters = append(parameters, map[string]any{
					"name":        f.JSONName,
					"in":          "query",
					"required":    false,
					"schema":      property(f),
					"description": filterDescription(f),
				})
			}
		}

		methodSpec := map[string]any{
			"summary": "Autogenerated by Bridgr",
			"responses": map[string]any{
				"200": map[string]any{
					"description": "Success",
				},
			},
		}
		if len(parameters) > 0 {
			methodSpec["parameters"] = parameters
		}
		if p.Method == "post" || p.Method == "put" || p.Method == "patch" {
			methodSpec["requestBody"] = map[string]any{
				"content": map[string]any{
					"application/json": map[string]any{
						"schema": map[string]any{
							"type":       "object",
							"properties": props,
						},
					},
				},
			}
		}
		pathItem.(map[string]any)[p.Method] = methodSpec
	}

	doc := map[string]any{
		"openapi": "3.0.0",
		"info": map[string]string{
			"title":   "Bridgr API",
			"version": "1.0.0",
		},
		"paths": paths,
	}
	return json.MarshalIndent(doc, "", "  ")
}

// extractPathParam returns the parameter name if the path contains {param}, else "".
func extractPathParam(path string) string {
	start := -1
	end := -1
	for i, c := range path {
		if c == '{' {
			start = i + 1
		}
		if c == '}' && start != -1 {
			end = i
			break
		}
	}
	if start != -1 && end != -1 && end > start {
		return path[start:end]
	}
	return ""
}

// filterDescription explains a filter parameter and the operators it accepts, which
// use the name[op]=value form that OpenAPI 3.0 can't express as separate parameters.
func filterDescription(f *brschema.Field) string {
	plain := "Exact match."
	if f.OpenAPIType == "string" && f.Format == "" {
		plain = "Case-insensitive substring match."
	}
	ops := brstore.OpsFor(f)
	forms := make([]string, len(ops))
	for i, op := range ops {
		forms[i] = fmt.Sprintf("%s[%s]", f.JSONName, op)
	}
	desc := fmt.Sprintf("%s Repeat to match any of several values. Operators: %s.", plain, strings.Join(forms, ", "))
	if slices.Contains(ops, brstore.In) {
		desc += fmt.Sprintf(" %s[in] takes a comma-separated list.", f.JSONName)
	}
	return desc
}

// pagingParameters documents the reserved list parameters limit, offset and sort.
func pagingParameters(model *brschema.Model) []map[string]any {
	sortable := []string{}
	if model.PrimaryKey != nil {
		sortable = append(sortable, model.PrimaryKey.JSONName)
	}
	for _, f := range model.Filterable {
		if !slices.Contains(sortable, f.JSONName) {
			sortable = append(sortable, f.JSONName)
		}
	}
	params := []map[string]any{
		{
			"name": "limit", "in": "query", "required": false,
			"schema":      map[string]any{"type": "integer", "minimum": 1},
			"description": "Page size. The server applies a default and a maximum. The response has X-Total-Count and a Link header with first, prev, next and last pages.",
		},
		{
			"name": "offset", "in": "query", "required": false,
			"schema":      map[string]any{"type": "integer", "minimum": 0},
			"description": "Number of records to skip.",
		},
	}
	if len(sortable) > 0 {
		params = append(params, map[string]any{
			"name": "sort", "in": "query", "required": false,
			"schema":      map[string]any{"type": "string"},
			"description": "Comma-separated fields, '-' for descending, e.g. -" + sortable[len(sortable)-1] + ". Sortable: " + strings.Join(sortable, ", ") + ".",
		})
	}
	return params
}
