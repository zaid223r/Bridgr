// Package api builds the OpenAPI document and serves the docs UI for registered routes.
package api

import (
	"encoding/json"
)

// BuildSpec renders the OpenAPI 3.0 document for every route registered with RegisterPath.
// It panics if a model lists a filterable field that does not exist.
func BuildSpec() ([]byte, error) {
	paths := map[string]any{}

	for _, p := range GetPaths() {
		model := mustSchema(p.Model)
		props := ReflectModel(p.Model)
		if pk := model.PrimaryKey; pk != nil {
			switch p.Method {
			case "post":
				delete(props, pk.JSONName)
			case "put":
				prop := property(pk)
				prop["readOnly"] = true
				props[pk.JSONName] = prop
			}
		}
		pathItem := paths[p.Path]
		if pathItem == nil {
			pathItem = map[string]any{}
			paths[p.Path] = pathItem
		}

		// Detect if path has a parameter (e.g., {id})
		var parameters []map[string]any
		if paramName := extractPathParam(p.Path); paramName != "" {
			parameters = append(parameters, map[string]any{
				"name":     paramName,
				"in":       "path",
				"required": true,
				"schema": map[string]any{
					"type": "string",
				},
			})
		}

		// Add filterable fields as query parameters for GET list endpoints
		if p.Method == "get" && extractPathParam(p.Path) == "" {
			for _, f := range model.Filterable {
				parameters = append(parameters, map[string]any{
					"name":     f.JSONName,
					"in":       "query",
					"required": false,
					"schema":   property(f),
				})
			}
		}

		methodSpec := map[string]any{
			"summary": "Autogenerated by Bridgr",
			"responses": map[string]any{
				"200": map[string]any{
					"description": "Success",
				},
			},
		}
		if len(parameters) > 0 {
			methodSpec["parameters"] = parameters
		}
		if p.Method == "post" || p.Method == "put" {
			methodSpec["requestBody"] = map[string]any{
				"content": map[string]any{
					"application/json": map[string]any{
						"schema": map[string]any{
							"type":       "object",
							"properties": props,
						},
					},
				},
			}
		}
		pathItem.(map[string]any)[p.Method] = methodSpec
	}

	doc := map[string]any{
		"openapi": "3.0.0",
		"info": map[string]string{
			"title":   "Bridgr API",
			"version": "1.0.0",
		},
		"paths": paths,
	}
	return json.MarshalIndent(doc, "", "  ")
}

// extractPathParam returns the parameter name if the path contains {param}, else "".
func extractPathParam(path string) string {
	start := -1
	end := -1
	for i, c := range path {
		if c == '{' {
			start = i + 1
		}
		if c == '}' && start != -1 {
			end = i
			break
		}
	}
	if start != -1 && end != -1 && end > start {
		return path[start:end]
	}
	return ""
}
